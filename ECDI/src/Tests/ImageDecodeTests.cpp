// ── T1：最小 PNG 解码（1×1 白）——精确像素 + Image 契约断言 ──
static void TestDecodePng1x1White()
{
	const Image img = Decode::DecodeMemory(kPng1x1White, kPngSize1x1White);
	EXPECT_EQ(img.width, 1);
	EXPECT_EQ(img.height, 1);
	EXPECT_EQ(img.stride, img.width * 4);                        // Image 契约：stride == width*4
	EXPECT_EQ(img.pixels.size(), static_cast<std::size_t>(img.height) * img.stride);
	// 1×1 不透明白 → BGRA = FF FF FF FF
	EXPECT_EQ(img.pixels[0], 0xFF);
	EXPECT_EQ(img.pixels[1], 0xFF);
	EXPECT_EQ(img.pixels[2], 0xFF);
	EXPECT_EQ(img.pixels[3], 0xFF);
}

// ── T2：半透明预乘验证（本 Phase 最重要测试——五合一契约锁死）──
static void TestDecodePng2x2Premultiply()
{
	const Image img = Decode::DecodeMemory(kPng2x2Alpha, kPngSize2x2Alpha);
	EXPECT_EQ(img.width, 2);
	EXPECT_EQ(img.height, 2);
	EXPECT_EQ(img.stride, img.width * 4);
	EXPECT_EQ(img.pixels.size(), static_cast<std::size_t>(img.height) * img.stride);

	// 第 0 行：不透明白 (255,255,255,255) → BGRA = FF FF FF FF；不透明黑 → 00 00 00 FF
	EXPECT_EQ(img.pixels[0], 0xFF);   // B
	EXPECT_EQ(img.pixels[1], 0xFF);   // G
	EXPECT_EQ(img.pixels[2], 0xFF);   // R
	EXPECT_EQ(img.pixels[3], 0xFF);   // A
	EXPECT_EQ(img.pixels[4], 0x00);   // B
	EXPECT_EQ(img.pixels[5], 0x00);   // G
	EXPECT_EQ(img.pixels[6], 0x00);   // R
	EXPECT_EQ(img.pixels[7], 0xFF);   // A

	// 第 1 行：R200/G100/B50/A128 → PBGRA：B' = 50×128/255 ≈ 25，G' = 100×128/255 ≈ 50，
	// R' = 200×128/255 ≈ 100，A' = 128（WIC 内部舍入 ±1 容差）
	const std::size_t base = img.stride;   // row 1 起点
	EXPECT_NEAR(img.pixels[base + 0], 25, 1);    // B'
	EXPECT_NEAR(img.pixels[base + 1], 50, 1);    // G'
	EXPECT_NEAR(img.pixels[base + 2], 100, 1);   // R'
	EXPECT_NEAR(img.pixels[base + 3], 128, 1);   // A（不预乘）
	EXPECT_NEAR(img.pixels[base + 4], 25, 1);
	EXPECT_NEAR(img.pixels[base + 5], 50, 1);
	EXPECT_NEAR(img.pixels[base + 6], 100, 1);
	EXPECT_NEAR(img.pixels[base + 7], 128, 1);
}

// ── T3：JPEG 解码（有损——只断言契约，不验具体像素）──
static void TestDecodeJpeg32x32Contract()
{
	const Image img = Decode::DecodeMemory(kJpeg32x32, kJpegSize32x32);
	EXPECT_EQ(img.width, 32);
	EXPECT_EQ(img.height, 32);
	EXPECT_EQ(img.stride, img.width * 4);
	EXPECT_EQ(img.pixels.size(), static_cast<std::size_t>(img.height) * img.stride);
}

// ── T4：非法字节 → 空 Image ──
static void TestDecodeInvalidBytes()
{
	const char garbage[] = "not an image";
	const Image img = Decode::DecodeMemory(
	    reinterpret_cast<const std::uint8_t*>(garbage), sizeof(garbage));
	EXPECT_EQ(img.width, 0);
	EXPECT_EQ(img.height, 0);
	EXPECT_TRUE(img.pixels.empty());
}

// ── T5：空输入三形态（nullptr/0、valid/0、nullptr/非0）——全部立即失败 ──
static void TestDecodeEmptyInputs()
{
	const std::uint8_t dummy = 0x89;
	EXPECT_EQ(Decode::DecodeMemory(nullptr, 0).width, 0);
	EXPECT_EQ(Decode::DecodeMemory(&dummy, 0).width, 0);
	EXPECT_EQ(Decode::DecodeMemory(nullptr, 5).width, 0);
}

// ── T6：文件不存在 → 空 Image ──
static void TestDecodeFileNotFound()
{
	const Image img = Decode::DecodeFile("Z:/nonexistent_dir/nonexistent.png");
	EXPECT_EQ(img.width, 0);
	EXPECT_TRUE(img.pixels.empty());
}

// ── T7：DrawImage 集成（解码结果 → PaintContext → RecordingBackend 命令断言）──
static void TestDecodeThenDrawImageCommand()
{
	const Image img = Decode::DecodeMemory(kPng1x1White, kPngSize1x1White);
	EXPECT_EQ(img.width, 1);

	std::vector<RenderCommand> commands;
	RecordingBackend backend;
	PaintContext pc(commands, backend);

	pc.DrawImage(Rect{ 0, 0, 4, 4 }, img);

	EXPECT_EQ(commands.size(), 1);
	EXPECT_TRUE(std::holds_alternative<DrawImageCommand>(commands[0]));
	const auto& cmd = std::get<DrawImageCommand>(commands[0]);
	EXPECT_EQ(cmd.image.width, 1);
	EXPECT_EQ(cmd.image.height, 1);
	EXPECT_EQ(cmd.image.pixels[0], 0xFF);   // 值拷贝进命令
}

// ── T8：失败日志路径（半自动验收——运行时人工核 OutputDebugString；不纳入全自动计数）──
static void TestDecodeFailureLogging()
{
	// 半自动：非法输入应产生 Error 日志（调试器输出窗口核）；此处仅验证不崩溃
	const Image img = Decode::DecodeFile("Z:/nonexistent_dir/nonexistent.png");
	EXPECT_EQ(img.width, 0);
}

