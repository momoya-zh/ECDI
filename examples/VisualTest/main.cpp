/// @brief 图片承载控件：OnPaint 里整图拉伸到控件矩形
class ImageHost final : public ECDI::Panel {
public:
	explicit ImageHost(Image image) : m_image(std::move(image)) { SetStretch(1); }

protected:
	void OnPaint(ECDI::PaintContext& ctx, int x, int y) override
	{
		Panel::OnPaint(ctx, x, y);
		if (!m_image.pixels.empty())
			ctx.DrawImage(ECDI::Rect{ static_cast<float>(x), static_cast<float>(y),
			                          static_cast<float>(GetWidth()), static_cast<float>(GetHeight()) },
			              m_image);
	}

private:
	Image m_image;
};

/// @brief 期望结果对照：直接代码构造 premultiplied BGRA（不经解码）——同尺寸/同内容
Image MakeExpectedGradient(unsigned int w, unsigned int h)
{
	Image img;
	img.width = static_cast<int>(w);
	img.height = static_cast<int>(h);
	img.stride = static_cast<int>(w * 4);
	img.pixels.resize(static_cast<std::size_t>(img.stride) * h);
	for (unsigned int y = 0; y < h; ++y) {
		for (unsigned int x = 0; x < w; ++x) {
			const auto a = static_cast<std::uint8_t>(255u * x / (w - 1));
			auto* px = img.pixels.data() + static_cast<std::size_t>(y) * img.stride + x * 4;
			// 期望解码结果：WIC PBGRA 输出 = 源 RGBA(255,0,0,a) 预乘 → B=0 G=0 R≈a A=a
			px[0] = 0; px[1] = 0; px[2] = a; px[3] = a;
		}
	}
	return img;
}

std::unique_ptr<ECDI::Widget> MakeText(const std::string& caption)
{
	auto label = std::make_unique<ECDI::Label>(caption);
	label->SetStretch(1);
	return label;
}

